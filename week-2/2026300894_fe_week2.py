# 5. Guess-and-Check (Exhaustive Enumeration) FE: Integer Square Root
# (From Week 2 Course Material)
x = int(input("Enter an integer to find its square root: "))
guess = 0

while guess**2 < abs(x):
    guess = guess + 1

if x < 0:
    print(x, "is negative, so it has no real square root.")
elif guess**2 == x:
    print("Square root of", x, "is", guess)
else:
    print(x, "is not a perfect square.")
