# 3. String Loop FE: Counting character occurrences with a for loop
# (From Week 2 Course Material Exercise 3)
'''
my_string = input("Enter a sentence: ")
target_char = input("Enter a character to count: ")
count = 0

for letter in my_string:
    if letter.lower() == target_char.lower():
        count += 1

print(f"The character '{target_char}' appeared {count} time(s).")
'''

