# 1. While Loop FE: Summing integers from 1 to N
# Demonstrates while loop condition, counter update, and loop termination
'''
n = int(input("Enter a positive integer N: "))
total_sum = 0
current = 1

while current <= n:
    total_sum += current
    current += 1

print("Sum of numbers from 1 to", n, "is:", total_sum)
'''

